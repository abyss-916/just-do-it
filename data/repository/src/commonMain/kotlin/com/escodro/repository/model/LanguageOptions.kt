package com.escodro.repository.model

/**
 * Enum to represent the app language selected by the user.
 */
enum class LanguageOptions {

    /**
     * System default language.
     */
    SYSTEM,

    /**
     * English.
     */
    ENGLISH,

    /**
     * Spanish.
     */
    SPANISH,

    /**
     * French.
     */
    FRENCH,

    /**
     * Portuguese (Brazil).
     */
    PORTUGUESE,

    /**
     * Chinese (Simplified).
     */
    CHINESE,
}
